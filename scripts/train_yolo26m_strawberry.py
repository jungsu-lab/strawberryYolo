#!/usr/bin/env python3
"""Train YOLO26m on the converted strawberry detection dataset."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def load_ultralytics_yolo() -> Any:
    try:
        from ultralytics import YOLO
    except ModuleNotFoundError as exc:
        raise SystemExit(
            "Ultralytics is required for actual YOLO training. "
            "Install local dependencies with: pip install -r requirements.txt"
        ) from exc
    return YOLO


def build_train_config(
    data_yaml: Path,
    model: str = "yolo26m.pt",
    imgsz: int = 1280,
    epochs: int = 120,
    batch: int = -1,
    device: str | int | None = None,
    project: Path = Path("runs/yolo26m"),
    name: str = "strawberry_stage_det",
    patience: int = 30,
) -> dict[str, Any]:
    config: dict[str, Any] = {
        "model": model,
        "data": str(data_yaml),
        "imgsz": imgsz,
        "epochs": epochs,
        "batch": batch,
        "project": str(project),
        "name": name,
        "patience": patience,
    }
    if device is not None and str(device) != "":
        config["device"] = device
    return config


def train_yolo26m_strawberry(config: dict[str, Any], dry_run: bool = False) -> dict[str, Any]:
    """Train with Ultralytics, or return the exact train config in dry-run mode."""

    if dry_run:
        return {"dry_run": True, "train_config": config}

    YOLO = load_ultralytics_yolo()
    model = YOLO(str(config["model"]))
    train_kwargs = {key: value for key, value in config.items() if key != "model"}
    result = model.train(**train_kwargs)
    return {"dry_run": False, "result": result}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Train YOLO26m on strawberry YOLO labels.")
    parser.add_argument("--data", type=Path, required=True, help="Dataset YAML generated by convert_aihub_strawberry_to_yolo.py.")
    parser.add_argument("--model", default="yolo26m.pt")
    parser.add_argument("--imgsz", type=int, default=1280)
    parser.add_argument("--epochs", type=int, default=120)
    parser.add_argument("--batch", type=int, default=-1)
    parser.add_argument("--device", default=None)
    parser.add_argument("--project", type=Path, default=Path("runs/yolo26m"))
    parser.add_argument("--name", default="strawberry_stage_det")
    parser.add_argument("--patience", type=int, default=30)
    parser.add_argument("--dry-run", action="store_true", help="Print the train config without importing Ultralytics.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    config = build_train_config(
        data_yaml=args.data,
        model=args.model,
        imgsz=args.imgsz,
        epochs=args.epochs,
        batch=args.batch,
        device=args.device,
        project=args.project,
        name=args.name,
        patience=args.patience,
    )
    result = train_yolo26m_strawberry(config, dry_run=args.dry_run)
    if args.dry_run:
        print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
